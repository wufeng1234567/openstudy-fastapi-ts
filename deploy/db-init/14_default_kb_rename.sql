-- 「我的空间」并入「知识库」（2026-10-22）
--
-- 背景
-- ----
-- 原设计里，「我的空间」是一个 `is_workspace=1` 的普通知识库，
-- 但它在侧栏有一个独立入口，同时又原样出现在知识库列表里，
-- 用户会看到「我的空间」出现两次，分不清该往哪传。
--
-- 现在统一成一个概念：**知识库**。
--   · 侧栏入口改名「知识库」；
--   · 页面升级为完整的多知识库管理（左库列表 / 右文档）；
--   · 默认库（is_workspace=1）作为「新建资料先落这里」的落脚点保留，
--     在列表里排最前、带「默认」徽标、不可改名/删除。
--
-- 这个脚本只做一件事：把已经写进库里的旧名字改掉。
-- ⚠️ 必须用 UPDATE 而不是只改代码里的常量 —— `name` 是创建时**固化**的，
--    改 `WORKSPACE_NAME` 只影响"以后新建的库"，存量数据不会跟着变。
-- ============================================================

UPDATE rag_knowledge_base
SET name = '默认知识库',
    description = '新传的资料先放这里，AI 会自己找',
    update_time = NOW()
WHERE is_workspace = 1
  AND name IN ('我的空间', '工作空间');
