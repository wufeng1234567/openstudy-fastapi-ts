-- 英语功能重构：给词书加归属（2026-10-23）
--
-- 背景
-- ----
-- `word_books` 原本是**全局资源**：没有 `user_id`，任何登录用户
-- 拿一串 id 就能删任意词书（见 `api/v1/words.py` 里那段"已知缺口"注释）。
-- 当时不敢加闸门，正是因为表上没有归属列 —— 一加 403 就会把普通用户
-- 删自己单词本的功能改瘫。
--
-- 现在英语功能重新开放给所有用户使用，必须：
--   1. 每本书有主人；
--   2. 列表只列自己的；
--   3. 增删改都校验归属。
--
-- 迁移策略
-- --------
-- · `user_id` 允许 NULL：历史数据（目前是 0 行）和"系统预置词书"可以不属于任何人；
--   NULL 的库对所有登录用户**只读可见、不可改删**，避免误伤。
-- · 老数据统一落到一个系统账号（user_id = 1，即 admin），保证不丢。
-- ============================================================

ALTER TABLE word_books
  ADD COLUMN IF NOT EXISTS user_id BIGINT;

COMMENT ON COLUMN word_books.user_id IS
  '词书归属用户；NULL = 系统预置（所有登录用户只读可见，不可改删）';

-- 存量数据归属到系统管理员，避免"没有主人"的孤岛数据
UPDATE word_books SET user_id = 1 WHERE user_id IS NULL;

-- 按用户查自己的词书是最高频查询
CREATE INDEX IF NOT EXISTS idx_word_books_user
  ON word_books (user_id)
  WHERE del_flag = '0';

-- 单词本身沿用 `book_id` 外键即可定位归属，不需要再加 user_id
-- （单词永远属于某本书，书有主人就等价于单词有主人）。
